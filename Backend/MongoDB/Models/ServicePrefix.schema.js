import mongoose from "mongoose";

const servicePrefixSchema = new mongoose.Schema(
  {
    code: {
      type: String,
      required: true,
      unique: true,
      uppercase: true,
      trim: true,
    },
    name: {
      type: String,
      trim: true,
    },
    isActive: {
      type: Boolean,
      default: true,
    },
  },
  { timestamps: true },
);

export const ServicePrefix = mongoose.model("ServicePrefix", servicePrefixSchema);
